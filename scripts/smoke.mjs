// Headless smoke test: loads /fly, flies, screenshots. Run with the production server up on :3100.
import { chromium } from "playwright";
const url = process.argv[2] ?? "http://localhost:3100/fly?drone=inspection&mode=angle&q=medium";
const out = process.argv[3] ?? "smoke";
const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") errors.push(`${m.type()}: ${m.text()}`); });
page.on("pageerror", (e) => errors.push("pageerror: " + e.message));
await page.goto(url);
await page.waitForSelector("canvas", { timeout: 60000 });
await page.waitForTimeout(2000);
await page.screenshot({ path: `${out}-1-ground.png` });
const hud = async () => page.evaluate(() => Object.fromEntries([...document.querySelectorAll("[data-k]")].map((e) => [e.dataset.k, e.textContent])));
await page.keyboard.down("ArrowUp");
await page.waitForTimeout(1300);
await page.keyboard.up("ArrowUp");
await page.waitForTimeout(1500);
console.log("after takeoff", JSON.stringify(await hud()));
await page.keyboard.press("c");
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}-2-chase.png` });
await page.keyboard.press("c");
await page.keyboard.down("z");
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}-3-fwd.png` });
console.log("flying fwd", JSON.stringify(await hud()));
await page.keyboard.up("z");
console.log("errors:", JSON.stringify(errors.slice(0, 8)));
await browser.close();
